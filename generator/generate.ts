// ─── Verification ─────────────────────────────────────────────────────

const API_CLIENT_DIR = path.resolve(import.meta.dir, '../../ui/packages/api-client/src/clients');

function extractExportedMethods(filePath: string): string[] {
  if (!fs.existsSync(filePath)) {
    return [];
  }
  const source = fs.readFileSync(filePath, 'utf-8');

  // Find the return { ... } block at the end of the factory function
  // We look for the last return { ... }; pattern
  const returnBlocks = source.matchAll(/return\s*\{([^}]+)\}/g);
  let lastMatch: string | null = null;
  for (const match of returnBlocks) {
    lastMatch = match[1]!;
  }

  if (!lastMatch) return [];

  // Extract method names from the return object
  return lastMatch
    .split(',')
    .map((s) => s.replace(/\/\/.*$/gm, '').trim()) // remove comments
    .filter((s) => s.length > 0 && !s.startsWith('//'))
    .map((s) => {
      // Handle "foo: bar" and just "foo"
      const colonIndex = s.indexOf(':');
      if (colonIndex > 0) {
        return s.substring(0, colonIndex).trim();
      }
      return s.trim();
    })
    .filter((s) => s.length > 0 && /^[a-zA-Z_]/.test(s));
}

type VerifyResult = {
  ok: boolean;
  errors: string[];
  warnings: string[];
};

function verifyRegistry(): VerifyResult {
  const errors: string[] = [];
  const warnings: string[] = [];

  for (const service of API_REGISTRY) {
    const clientDir = path.join(API_CLIENT_DIR, service.sourceDir);

    if (!fs.existsSync(clientDir)) {
      warnings.push(`[${service.name}] Source directory not found: ${clientDir}`);
      continue;
    }

    // Verify direct methods on the main client file
    const mainFile = path.join(clientDir, service.clientFile);
    const mainMethods = extractExportedMethods(mainFile);

    for (const method of service.methods) {
      // Skip methods that are actually on sub-objects (handled by sub-groups)
      if (!mainMethods.includes(method.name)) {
        // Check if it might be a private method (prefixed with _)
        if (!mainMethods.includes(`_${method.name}`)) {
          errors.push(`[${service.name}] Method '${method.name}' not found in ${service.clientFile}. Available: ${mainMethods.join(', ')}`);
        }
      }
    }

    // Verify sub-group methods
    for (const group of service.subGroups) {
      const subFile = path.join(clientDir, group.sourceFile);
      const subMethods = extractExportedMethods(subFile);

      if (subMethods.length === 0) {
        warnings.push(`[${service.name}.${group.name}] No methods found in ${group.sourceFile}`);
        continue;
      }

      for (const method of group.methods) {
        if (!subMethods.includes(method.name)) {
          errors.push(`[${service.name}.${group.name}] Method '${method.name}' not found in ${group.sourceFile}. Available: ${subMethods.join(', ')}`);
        }
      }

      // Warn about methods in source but not in registry
      const registeredNames = new Set(group.methods.map((m) => m.name));
      for (const srcMethod of subMethods) {
        if (!registeredNames.has(srcMethod) && !srcMethod.startsWith('_')) {
          warnings.push(`[${service.name}.${group.name}] Method '${srcMethod}' exists in source but not in registry`);
        }
      }
    }

    // Warn about methods in source but not in registry (direct methods)
    const registeredDirectNames = new Set(service.methods.map((m) => m.name));
    // For the main client, also collect sub-group names (they appear in return)
    const subGroupNames = new Set(service.subGroups.map((g) => g.name));
    for (const srcMethod of mainMethods) {
      if (!registeredDirectNames.has(srcMethod) && !subGroupNames.has(srcMethod) && !srcMethod.startsWith('_')) {
        warnings.push(`[${service.name}] Method '${srcMethod}' exists in source but not in registry`);
      }
    }
  }

  return {
    ok: errors.length === 0,
    errors,
    warnings,
  };
}

// ─── Code Generation ──────────────────────────────────────────────────

function camelToKebab(name: string): string {
  return name.replace(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase();
}

function kebabToCamel(name: string): string {
  return name.replace(/-([a-z])/g, (_, c) => c.toUpperCase());
}

function pascalCase(name: string): string {
  return name.split('-').map((s) => s[0]!.toUpperCase() + s.slice(1)).join('');
}

