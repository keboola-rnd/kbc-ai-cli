// ─── Logical Unit Types ──────────────────────────────────────────────

type UnitArgDef = {
  name: string;
  description: string;
  required: boolean;
  type: 'string' | 'number';
};

type UnitOptionDef = {
  name: string;
  description: string;
  type: 'string' | 'number' | 'boolean';
  required?: boolean;
  defaultValue?: string | number | boolean;
};

type UnitTableColumn = {
  key: string;
  label?: string;
  maxWidth?: number;
};

type UnitTable = {
  emptyMessage: string;
  columns: UnitTableColumn[];
  /** If set, the response is an array of components; extract this field's array from each */
  flatten?: string;
};

type UnitCommandDef = {
  name: string;
  description: string;
  service: string;
  subGroup?: string;
  atomicRef: string;
  httpMethod: string;
  urlTemplate: string;
  idCount: number;
  args: UnitArgDef[];
  options: UnitOptionDef[];
  table?: UnitTable;
  /** Hardcoded positional args injected into the URL template (e.g. { "0": "keboola.orchestrator" }) */
  hardcodedArgs?: Record<string, string>;
  /** Maps CLI arg names to URL template positions (e.g. { "flowId": 1 }) */
  argMapping?: Record<string, number>;
  /** Additional query params merged as defaults */
  queryDefaults?: Record<string, string>;
  /** Build a custom request body; $varName references args/options */
  buildBody?: Record<string, string>;
};

type UnitDef = {
  name: string;
  description: string;
  skillDescription?: string;
  commands: UnitCommandDef[];
};

type LogicalUnitsFile = {
  units: UnitDef[];
};

