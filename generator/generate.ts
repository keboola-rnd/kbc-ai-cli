// ─── Main ─────────────────────────────────────────────────────────────

async function main() {
  const verifyOnly = process.argv.includes('--verify-only');

  console.log('API Registry Stats:');
  const { total, byService } = countMethods();
  for (const [name, count] of Object.entries(byService)) {
    console.log(`  ${name}: ${count} methods`);
  }
  console.log(`  TOTAL: ${total} methods`);
  console.log('');

  // Verify registry against source
  console.log('Verifying registry against api-client source...');
  const result = verifyRegistry();

  for (const warning of result.warnings) {
    console.log(`  WARN: ${warning}`);
  }
  for (const error of result.errors) {
    console.log(`  ERROR: ${error}`);
  }

  if (!result.ok) {
    console.error('\nRegistry verification failed! Fix errors above.');
    process.exit(1);
  }

  console.log(`\nVerification passed (${result.warnings.length} warnings).`);

  if (verifyOnly) {
    console.log('Verify-only mode, skipping generation.');
    return;
  }

  // Generate files
  console.log('\nGenerating CLI commands...');

  // Ensure output directory exists
  fs.mkdirSync(GENERATED_DIR, { recursive: true });

  // Generate service files
  for (const service of API_REGISTRY) {
    const filePath = path.join(GENERATED_DIR, `${service.cliName}.ts`);
    fs.writeFileSync(filePath, generateServiceFile(service));
    const methodCount = service.methods.length + service.subGroups.reduce((sum, g) => sum + g.methods.length, 0);
    console.log(`  ${service.cliName}.ts (${methodCount} commands)`);
  }

  // Generate registry file
  const registryPath = path.join(GENERATED_DIR, '_registry.ts');
  fs.writeFileSync(registryPath, generateRegistryFile());
  console.log(`  _registry.ts`);

  // Generate index file
  const indexPath = path.join(GENERATED_DIR, 'index.ts');
  fs.writeFileSync(indexPath, generateIndexFile());
  console.log(`  index.ts`);

  console.log(`\nGeneration complete! ${total} atomic commands across ${API_REGISTRY.length} services.`);

  // ─── Layer 2: Logical Units ─────────────────────────────────────
  console.log('\nGenerating Layer 2 logical units...');

  const logicalUnits = loadLogicalUnits();

  // Validate atomicRef references
  const unitValidation = validateLogicalUnits(logicalUnits.units);
  for (const err of unitValidation.errors) {
    console.log(`  ERROR: ${err}`);
  }
  if (!unitValidation.ok) {
    console.error('\nLogical unit validation failed! Fix atomicRef errors above.');
    process.exit(1);
  }
  console.log(`  Validation passed (${logicalUnits.units.length} units).`);

  // Ensure units output directory exists
  fs.mkdirSync(UNITS_DIR, { recursive: true });

  // Generate unit files
  for (const unit of logicalUnits.units) {
    const filePath = path.join(UNITS_DIR, `${unit.name}.ts`);
    fs.writeFileSync(filePath, generateUnitFile(unit));
    console.log(`  units/${unit.name}.ts (${unit.commands.length} commands)`);
  }

  // Generate units index (named _generated.ts to avoid conflict with hand-written index.ts)
  const unitsIndexPath = path.join(UNITS_DIR, '_generated.ts');
  fs.writeFileSync(unitsIndexPath, generateUnitsIndexFile(logicalUnits.units));
  console.log(`  units/_generated.ts`);

  const totalUnitCommands = logicalUnits.units.reduce((s, u) => s + u.commands.length, 0);
  console.log(`\nLayer 2 complete! ${totalUnitCommands} unit commands across ${logicalUnits.units.length} logical units.`);

  // Generate SKILL.md
  const skillMd = generateSkillMd(logicalUnits);
  const skillPath = path.resolve(import.meta.dir, '../SKILL.md');
  fs.writeFileSync(skillPath, skillMd);
  console.log(`\nGenerated SKILL.md`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
